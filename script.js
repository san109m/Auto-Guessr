let autoActual = null;
let pistaActual = 0;

const pistaEls = [...document.querySelectorAll(".pista")];
const input = document.getElementById("adivinador");
const sugerenciasWrap = document.getElementById("sugerencias");
const btnSiguiente = document.getElementById("btnSiguiente");
const btnAdivinar = document.getElementById("btnAdivinar");
const btnReiniciar = document.getElementById("btnReiniciar");
const resultadoDiv = document.getElementById("resultado");
const contadorSpan = document.getElementById("contador");

const modelos = AUTOS.map(a => a.modelo);

/* ========================== */

function elegirAutoAleatorio(){
  autoActual = AUTOS[Math.floor(Math.random()*AUTOS.length)];
  pistaActual = 0;
  pistaEls.forEach(el => { el.style.display="none"; el.innerHTML=""; });
  mostrarPista(0);
  resultadoDiv.style.display="none";
  input.value="";
  sugerenciasWrap.innerHTML="";
  btnSiguiente.disabled=false;
  btnAdivinar.disabled=false;
  contadorSpan.textContent="1";
}

function mostrarPista(i){
  const el = pistaEls[i];
  el.style.display = "block";
  el.classList.remove("animar"); 
  void el.offsetWidth;
  el.classList.add("animar");  

  if (i === 5) {
    const nombre = autoActual.modelo.replace(/\s+/g, "").toUpperCase();
    el.innerHTML = `
      PISTA 6:<br>
      <img src="imagenes/${nombre}.jpeg" style="max-width:160px; border-radius:12px;">
    `;
    return;
  }

  el.textContent = "PISTA " + (i+1) + ": " + autoActual.pistas[i];
}

btnSiguiente.onclick = ()=>{
  if(pistaActual < 5){
    pistaActual++;
    mostrarPista(pistaActual);
    contadorSpan.textContent = (pistaActual+1);
  }
  if(pistaActual === 5) btnSiguiente.disabled = true;
};

btnAdivinar.onclick = () => {
  resultadoDiv.style.display = "block";
  resultadoDiv.classList.remove("correcto", "incorrecto");

  const txt = input.value.trim().toLowerCase();
  const correcto = autoActual.modelo.toLowerCase();

  if(txt === correcto){
    resultadoDiv.classList.add("correcto");
    resultadoDiv.textContent = "¡Correcto! Era " + autoActual.modelo;
  } else {
    resultadoDiv.classList.add("incorrecto");
    resultadoDiv.textContent = "Incorrecto. Era " + autoActual.modelo;
  }

  btnSiguiente.disabled = true;
  btnAdivinar.disabled = true;
};


btnReiniciar.onclick = elegirAutoAleatorio;

/* Autocompletado */
input.addEventListener("input", ()=>{
  const q = input.value.toLowerCase();
  sugerenciasWrap.innerHTML="";
  if(!q) return;

  modelos.filter(m=>m.toLowerCase().includes(q)).slice(0,6).forEach(m=>{
    const div=document.createElement("div");
    div.className="sugerencia";
    div.textContent=m.toUpperCase();
    div.onclick=()=>{ input.value=m; sugerenciasWrap.innerHTML=""; };
    sugerenciasWrap.appendChild(div);
  });
});

/* Enter = adivinar */
input.addEventListener("keydown",(e)=>{
  if(e.key==="Enter"){
    e.preventDefault();
    btnAdivinar.click();
  }
});

window.onload = elegirAutoAleatorio;